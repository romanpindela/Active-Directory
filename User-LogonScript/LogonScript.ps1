# PrzykĹ‚ad: Mapowanie dysku sieciowego dla uĹĽytkownika
$DriveLetter = "Z:"
$DriveName   = "Z"
$NetworkPath = "\\serwer\zasob"

# Sprawdzenie czy dysk nie jest juĹĽ zamapowany i mapowanie
if (!(Test-Path $DriveLetter)) {
    New-PSDrive -Name $DriveName -PSProvider FileSystem -Root $NetworkPath -Persist -Scope Global -ErrorAction SilentlyContinue | Out-Null
}

# Weryfikacja sukcesu (zapis do logu lokalnego C:\Temp\LogonStatus.txt)
$LogPath = "C:\Temp\LogonStatus.txt"
$LogDir  = Split-Path -Path $LogPath -Parent
if (!(Test-Path $LogDir)) {
    New-Item -ItemType Directory -Path $LogDir -Force | Out-Null
}
"Zalogowano pomyĹ›lnie dnia $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss') | UĹĽytkownik: $env:USERDOMAIN\$env:USERNAME | Komputer: $env:COMPUTERNAME | Dysk: $DriveLetter -> $NetworkPath" | Out-File -Append -FilePath $LogPath -Encoding UTF8

# Dodatkowy zapis do centralnego katalogu logĂłw C:\Logs
$CentralLogDir = "C:\Logs"
if (!(Test-Path $CentralLogDir)) {
    New-Item -ItemType Directory -Path $CentralLogDir -Force -ErrorAction SilentlyContinue | Out-Null
}
$CentralLogFile = Join-Path -Path $CentralLogDir -ChildPath "$((Get-Date).ToString('yyyyMMdd_HHmmss'))-User-LogonScript-$env:COMPUTERNAME-$env:USERNAME.logs"
"[$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss.fff')] [SUCCESS] Zalogowano pomyĹ›lnie dnia $(Get-Date) (User: $env:USERDOMAIN\$env:USERNAME, Drive: $DriveLetter -> $NetworkPath)" | Out-File -Append -FilePath $CentralLogFile -Encoding UTF8 -ErrorAction SilentlyContinue
